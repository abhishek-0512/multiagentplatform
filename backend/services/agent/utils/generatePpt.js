// ==================== PROCESS / ROADMAP SLIDE ====================
function addProcessSlide(ppt, slideData, page, total) {
    const slide = ppt.addSlide()
    setupSlideHeaderFooter(slide, ppt, slideData.title, slideData.tagline || "Step-by-Step Workflow", page, total)

    const steps = slideData.steps || []
    const totalSteps = Math.min(steps.length, 4)
    const cardWidth = (11.7 - (totalSteps - 1) * 0.3) / totalSteps

    steps.slice(0, totalSteps).forEach((st, i) => {
        const x = 0.8 + i * (cardWidth + 0.3)

        // Step Card
        slide.addShape(ppt.ShapeType.roundRect, {
            x,
            y: 1.8,
            w: cardWidth,
            h: 4.6,
            fill: { color: PALETTE.cardBg },
            line: { color: PALETTE.cardBorder, width: 1.5 },
            radius: 0.1
        })

        // Step Number Badge
        slide.addShape(ppt.ShapeType.roundRect, {
            x: x + (cardWidth - 0.8) / 2,
            y: 2.1,
            w: 0.8,
            h: 0.8,
            fill: { color: PALETTE.primary },
            line: { color: PALETTE.primary },
            radius: 0.15
        })
        slide.addText(`${st.step || i + 1}`, {
            x: x + (cardWidth - 0.8) / 2,
            y: 2.1,
            w: 0.8,
            h: 0.8,
            align: "center",
            valign: "middle",
            fontSize: 18,
            bold: true,
            color: PALETTE.white
        })

        // Step Title
        slide.addText(st.title || `Phase ${i + 1}`, {
            x: x + 0.15,
            y: 3.1,
            w: cardWidth - 0.3,
            h: 0.6,
            align: "center",
            fontSize: 14,
            bold: true,
            color: PALETTE.secondary,
            fit: "shrink"
        })

        // Step Description
        slide.addText(st.description || st.text || "", {
            x: x + 0.2,
            y: 3.8,
            w: cardWidth - 0.4,
            h: 2.3,
            align: "center",
            fontSize: 12,
            color: PALETTE.textDark,
            fit: "shrink"
        })
    })
}

// ==================== METRICS / STATS SLIDE ====================
function addMetricsSlide(ppt, slideData, page, total) {
    const slide = ppt.addSlide()
    setupSlideHeaderFooter(slide, ppt, slideData.title, slideData.tagline || "Key Metrics & Impact", page, total)

    const metrics = slideData.metrics || []
    const totalMetrics = Math.min(metrics.length, 3)
    const cardWidth = (11.7 - (totalMetrics - 1) * 0.4) / totalMetrics

    metrics.slice(0, totalMetrics).forEach((m, i) => {
        const x = 0.8 + i * (cardWidth + 0.4)

        // Stat Card
        slide.addShape(ppt.ShapeType.roundRect, {
            x,
            y: 1.8,
            w: cardWidth,
            h: 3.2,
            fill: { color: i === 1 ? "EEF2FF" : PALETTE.cardBg },
            line: { color: i === 1 ? "C7D2FE" : PALETTE.cardBorder, width: 1.5 },
            radius: 0.12
        })

        // Big Metric Number
        slide.addText(m.value || "100%", {
            x: x + 0.2,
            y: 2.2,
            w: cardWidth - 0.4,
            h: 1.0,
            align: "center",
            fontSize: 34,
            bold: true,
            color: i === 1 ? PALETTE.accent : PALETTE.primary,
            fit: "shrink"
        })

        // Metric Label
        slide.addText(m.label || "Key Metric", {
            x: x + 0.2,
            y: 3.4,
            w: cardWidth - 0.4,
            h: 0.8,
            align: "center",
            fontSize: 13,
            bold: true,
            color: PALETTE.textDark,
            fit: "shrink"
        })
    })

    // Bottom Summary Card
    if (slideData.summary || slideData.points?.length) {
        const summaryText = slideData.summary || slideData.points?.join(" • ")
        slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.8,
            y: 5.3,
            w: 11.7,
            h: 1.3,
            fill: { color: "F1F5F9" },
            line: { color: "CBD5E1" },
            radius: 0.08
        })
        slide.addText(summaryText, {
            x: 1.1,
            y: 5.4,
            w: 11.1,
            h: 1.1,
            fontSize: 13,
            color: PALETTE.textDark,
            valign: "middle",
            fit: "shrink"
        })
    }
}

