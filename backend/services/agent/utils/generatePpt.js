import pptxgen from "pptxgenjs"

const PALETTE = {
    primary: "2563EB",     // Royal Blue
    primaryDark: "1D4ED8",
    secondary: "0F172A",   // Slate 900
    cardBg: "F8FAFC",      // Slate 50
    cardBorder: "E2E8F0",  // Slate 200
    accent: "6366F1",      // Indigo
    accentLight: "EEF2FF",
    success: "10B981",     // Emerald
    successLight: "ECFDF5",
    textDark: "0F172A",
    textMuted: "64748B",
    white: "FFFFFF",
    gradientStart: "1E293B",
    gradientEnd: "0F172A"
}

export const generatePpt = async (data) => {
    const ppt = new pptxgen()
    ppt.layout = "LAYOUT_WIDE" // 13.33 x 7.5 inches
    ppt.author = "Nexora Platform"
    ppt.title = data.title || "Presentation"
    ppt.subject = data.subtitle || data.title
    ppt.company = "Nexora"
    ppt.theme = {
        headFontFace: "Arial",
        bodyFontFace: "Calibri"
    }

    // 1. Cover Slide
    addCover(ppt, data)

    // 2. Content Slides with layout discrimination
    const slides = data?.slides || []
    slides.forEach((s, idx) => {
        const slideType = s.type || detectSlideType(s)
        const page = idx + 1
        const total = slides.length

        switch (slideType) {
            case "comparison":
                addComparisonSlide(ppt, s, page, total)
                break
            case "process":
                addProcessSlide(ppt, s, page, total)
                break
            case "stats":
            case "metrics":
                addMetricsSlide(ppt, s, page, total)
                break
            case "architecture":
                addArchitectureSlide(ppt, s, page, total)
                break
            default:
                addConceptSlide(ppt, s, page, total)
                break
        }
    })

    // 3. Closing Slide
    addThankYou(ppt, data)

    return ppt
}

function detectSlideType(slide) {
    if (slide.comparison || (slide.leftTitle && slide.rightTitle)) return "comparison"
    if (slide.steps && slide.steps.length > 0) return "process"
    if (slide.metrics && slide.metrics.length > 0) return "stats"
    if (slide.components && slide.components.length > 0) return "architecture"
    return "concept"
}

// ==================== COVER SLIDE ====================
function addCover(ppt, data) {
    const slide = ppt.addSlide()
    slide.background = { color: PALETTE.secondary }

    // Top Accent Bar
    slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: 13.33,
        h: 0.25,
        fill: { color: PALETTE.primary },
        line: { color: PALETTE.primary }
    })

    // Badge
    slide.addShape(ppt.ShapeType.roundRect, {
        x: 1.0,
        y: 1.6,
        w: 2.2,
        h: 0.4,
        fill: { color: PALETTE.primary },
        line: { color: PALETTE.primary },
        radius: 0.08
    })
    slide.addText("PRESENTATION", {
        x: 1.0,
        y: 1.6,
        w: 2.2,
        h: 0.4,
        align: "center",
        color: PALETTE.white,
        bold: true,
        fontSize: 11,
        fontFace: "Arial"
    })

    // Main Title
    slide.addText(data.title || "Modern Presentation", {
        x: 1.0,
        y: 2.3,
        w: 11.33,
        h: 1.6,
        color: PALETTE.white,
        bold: true,
        fontSize: 32,
        fontFace: "Arial",
        fit: "shrink"
    })

    // Subtitle
    if (data.subtitle) {
        slide.addText(data.subtitle, {
            x: 1.0,
            y: 4.1,
            w: 11.33,
            h: 0.8,
            color: "94A3B8",
            fontSize: 16,
            fontFace: "Calibri",
            fit: "shrink"
        })
    }

    // Divider Line
    slide.addShape(ppt.ShapeType.line, {
        x: 1.0,
        y: 5.2,
        w: 4.0,
        h: 0,
        line: { color: PALETTE.primary, width: 2 }
    })

    // Footer
    slide.addText("Generated by Nexora Platform", {
        x: 1.0,
        y: 6.7,
        w: 8.0,
        h: 0.3,
        color: "64748B",
        fontSize: 10,
        fontFace: "Calibri"
    })
}

// Base header & footer on content slides
function setupSlideHeaderFooter(slide, ppt, title, category, page, total) {
    slide.background = { color: PALETTE.white }

    // Category / Tagline
    if (category) {
        slide.addText(category.toUpperCase(), {
            x: 0.8,
            y: 0.35,
            w: 10.0,
            h: 0.25,
            fontSize: 10,
            bold: true,
            color: PALETTE.primary,
            fontFace: "Arial"
        })
    }

    // Slide Title
    slide.addText(title, {
        x: 0.8,
        y: category ? 0.6 : 0.4,
        w: 11.7,
        h: 0.55,
        fontSize: 22,
        bold: true,
        color: PALETTE.secondary,
        fontFace: "Arial"
    })

    // Top subtle divider
    slide.addShape(ppt.ShapeType.line, {
        x: 0.8,
        y: 1.25,
        w: 11.7,
        h: 0,
        line: { color: PALETTE.cardBorder, width: 1.0 }
    })

    // Footer
    slide.addText("Nexora Platform", {
        x: 0.8,
        y: 6.9,
        w: 4.0,
        h: 0.3,
        fontSize: 9,
        color: PALETTE.textMuted,
        fontFace: "Calibri"
    })

    slide.addText(`${page} / ${total}`, {
        x: 11.0,
        y: 6.9,
        w: 1.5,
        h: 0.3,
        align: "right",
        fontSize: 9,
        bold: true,
        color: PALETTE.textMuted,
        fontFace: "Calibri"
    })
}

// ==================== CONCEPT / STANDARD SLIDE ====================
function addConceptSlide(ppt, slideData, page, total) {
    const slide = ppt.addSlide()
    setupSlideHeaderFooter(slide, ppt, slideData.title, slideData.tagline || slideData.category, page, total)

    const points = slideData.points || []
    const totalPoints = Math.min(points.length, 5)

    points.slice(0, totalPoints).forEach((point, i) => {
        const y = 1.5 + (i * 0.95)

        // Card Container
        slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.8,
            y,
            w: 11.7,
            h: 0.8,
            fill: { color: i === 0 ? "F0F7FF" : PALETTE.cardBg },
            line: { color: i === 0 ? "BFDBFE" : PALETTE.cardBorder, width: 1 },
            radius: 0.08
        })

        // Number Badge
        slide.addShape(ppt.ShapeType.ellipse, {
            x: 1.05,
            y: y + 0.22,
            w: 0.35,
            h: 0.35,
            fill: { color: i === 0 ? PALETTE.primary : "E2E8F0" },
            line: { color: i === 0 ? PALETTE.primary : "CBD5E1" }
        })
        slide.addText(`${i + 1}`, {
            x: 1.05,
            y: y + 0.22,
            w: 0.35,
            h: 0.35,
            align: "center",
            valign: "middle",
            fontSize: 11,
            bold: true,
            color: i === 0 ? PALETTE.white : PALETTE.secondary,
            fontFace: "Arial"
        })

        // Text
        slide.addText(point, {
            x: 1.55,
            y: y + 0.12,
            w: 10.7,
            h: 0.55,
            fontSize: 14,
            color: PALETTE.textDark,
            fontFace: "Calibri",
            valign: "middle",
            fit: "shrink"
        })
    })

    // Takeaway callout if present
    if (slideData.keyTakeaway) {
        slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.8,
            y: 6.25,
            w: 11.7,
            h: 0.55,
            fill: { color: "FEF3C7" },
            line: { color: "FDE68A" },
            radius: 0.06
        })
        slide.addText(`💡 Key Takeaway: ${slideData.keyTakeaway}`, {
            x: 1.0,
            y: 6.25,
            w: 11.3,
            h: 0.55,
            fontSize: 11,
            bold: true,
            color: "92400E",
            fontFace: "Calibri",
            valign: "middle",
            fit: "shrink"
        })
    }
}

